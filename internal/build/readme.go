// ImagePaths lists the PNG specimens the README uses (relative to the package).
func ImagePaths(b *brand.Brand) []string {
	var out []string
	for _, th := range b.Themes {
		out = append(out, pathJoin(b.Config.Readme.Assets, "type-"+th.Name+".png"),
			pathJoin(b.Config.Readme.Assets, "components-"+th.Name+".png"))
	}
	return out
}

type sheet struct {
	b     *brand.Brand
	rules *brand.Rules
	files []File
	w     bytes.Buffer
}

// rel turns a package path into a path relative to the README.
func (s *sheet) rel(p string) string {
	dir := path.Dir(s.b.Config.Readme.File)
	if dir == "." {
		return p
	}
	r, err := filepath.Rel(filepath.FromSlash(dir), filepath.FromSlash(p))
	if err != nil {
		return p
	}
	return filepath.ToSlash(r)
}

func (s *sheet) asset(name string, data []byte) string {
	p := pathJoin(s.b.Config.Readme.Assets, name)
	for i, f := range s.files {
		if f.Path == p {
			s.files[i].Data = data
			return p
		}
	}
	s.files = append(s.files, File{Path: p, Data: data})
	return p
}

// img writes one sheet picture that shows every theme.
func (s *sheet) img(p, alt string) {
	fmt.Fprintf(&s.w, "<img alt=\"%s\" src=\"%s\">\n", html.EscapeString(alt), s.rel(p))
}

// themedPNGs writes a PNG specimen per theme, one under the other, each
// labelled and shown at true size.
func (s *sheet) themedPNGs(kind, alt string) {
	for _, th := range s.b.Themes {
		fmt.Fprintf(&s.w, "**%s**\n\n<img alt=\"%s, %s theme\" src=\"%s\" width=\"%d\">\n\n", html.EscapeString(themeLabel(th)), html.EscapeString(alt), html.EscapeString(th.Config.Label),
			s.rel(pathJoin(s.b.Config.Readme.Assets, kind+"-"+th.Name+".png")), SpecimenWidth)
	}
}

func (s *sheet) p(format string, a ...any) { fmt.Fprintf(&s.w, format, a...) }

// Sheet writes the README brand sheet and its SVG assets.
func Sheet(b *brand.Brand) ([]File, error) {
	rules, err := b.Default().Rules()
	if err != nil {
		return nil, err
	}
	s := &sheet{b: b, rules: rules}
	c := b.Config
	s.p("<!-- %s -->\n\n# %s\n\n", generatedBy(b), c.Name)
	if c.Description != "" {
		s.p("%s\n\n", c.Description)
	}
	var names []string
	for _, th := range b.Themes {
		n := th.Config.Label
		if th.Config.Default {
			n += " (default)"
		}
		names = append(names, n)
	}
	s.p("Themes: %s. Every picture shows each theme, labelled; values are in the tables.\n\n", strings.Join(names, ", "))
	s.p("Source: [`%s`](%s) (DTCG 2025.10). Every file below is generated by `brandkit build`; `brandkit check` checks the rules.\n\n", c.Resolver, s.rel(c.Resolver))
	s.p("1. [Logo and clear space](#logo-and-clear-space)\n2. [Colour](#colour)\n3. [Type](#type)\n4. [Spacing and radius](#spacing-and-radius)\n5. [Icons](#icons)\n6. [Components](#components)\n7. [Brand assets](#brand-assets)\n8. [Do and don't](#do-and-dont)\n9. [Install](#install)\n\n")
	steps := []func() error{s.logo, s.colour, s.typeSection, s.scale, s.icons, s.components, s.assets, s.doDont, s.install}
	for _, f := range steps {
		if err := f(); err != nil {
			return nil, err
		}
	}
	s.files = append(s.files, File{Path: c.Readme.File, Data: s.w.Bytes()})
	return s.files, nil
}

var viewBoxRe = regexp.MustCompile(`viewBox="\s*([-\d.]+)[\s,]+([-\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)\s*"`)
var svgOpenRe = regexp.MustCompile(`(?s)<svg\b[^>]*>`)

func (s *sheet) logo() error {
	s.p("## Logo and clear space\n\n")
	r := s.rules
	if len(r.Lockup) == 0 {
		s.p("The brand declares no lockup.\n\n")
		return nil
	}
	for _, th := range s.b.Themes {
		if r.Lockup[th.Name] == "" {
			return fmt.Errorf("brand rules: no lockup for theme %s", th.Name)
		}
	}
	s.p("Use the lockup made for the ground it sits on:\n\n| Theme | Lockup |\n|---|---|\n")
	for _, th := range s.b.Themes {
		s.p("| %s | [`%s`](%s) |\n", th.Config.Label, r.Lockup[th.Name], s.rel(r.Lockup[th.Name]))
	}
	s.p("\n")
	ratio := 0.0
	if r.ClearSpace != nil {
		ratio = r.ClearSpace.Ratio
	}
	svg, err := s.clearSpaceSheet(ratio)
	if err != nil {
		return err
	}
	s.img(s.asset("clearspace.svg", svg), "Each theme's lockup on its ground, with its clear space dashed")
	s.p("\n")
	if r.ClearSpace != nil {
		s.p("**Clear space:** %s× the %s on every side (the dashed box).", brand.Num(r.ClearSpace.Ratio), r.ClearSpace.Of)
		if r.ClearSpace.Note != "" {
			s.p(" %s", r.ClearSpace.Note)
		}
		s.p("\n\n")
	}
	if r.Mark != "" {
		s.p("The mark on its own: [`%s`](%s).\n\n", r.Mark, s.rel(r.Mark))
	}
	return nil
}

// roleHex is a DaisyUI role's hex in a theme, for drawing sheet assets.
func (s *sheet) roleHex(th *brand.Theme, role, fallback string) string {
	dt, err := DaisyVars(th, "hex")
	if err != nil {
		return fallback
	}
	for _, d := range dt.Vars {
		if d.Name == "color-"+role {
			return d.Value
		}
	}
	return fallback
}

// swatch writes one swatch file per distinct colour.
func (s *sheet) swatch(hex string) string {
	p := pathJoin(s.b.Config.Readme.Assets, "sw-"+strings.TrimPrefix(hex, "#")+".svg")
	for _, f := range s.files {
		if f.Path == p {
			return p
		}
	}
	s.files = append(s.files, File{Path: p, Data: swatchSVG(hex)})
	return p
}

func swatchSVG(hex string) []byte {
	return []byte(fmt.Sprintf(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24"><rect x="0.5" y="0.5" width="23" height="23" rx="4" fill="%s" stroke="#8c959f" stroke-opacity="0.6"/></svg>`+"\n", hex))
}

func colourText(t *dtcg.Token) (string, string, error) {
	hex, err := brand.ColorCSS(t.Value, "hex")
	if err != nil {
		return "", "", err
	}
	o := t.Value.(*dtcg.Object)
	comps, _ := o.Values["components"].([]any)
	parts := make([]string, len(comps))
	for i, c := range comps {
		if f, ok := c.(float64); ok {
			parts[i] = brand.Num(f)
		} else {
			parts[i] = "none"
		}
	}
	return hex, fmt.Sprintf("%s(%s)", o.String("colorSpace"), strings.Join(parts, " ")), nil
}

func (s *sheet) swatchCell(th *brand.Theme, name string) (string, error) {
	t := th.Tokens.Get(name)
	if t == nil || t.Type != "color" {
		return "", fmt.Errorf("theme %s: %s isn't a colour token", th.Name, name)
	}
	hex, authored, err := colourText(t)
	if err != nil {
		return "", err
	}
	p := s.swatch(hex)
	alias := ""
	if t.Alias != "" {
		alias = fmt.Sprintf(" ← `%s`", t.Alias)
	}
	return fmt.Sprintf(`<img src="%s" width="16" height="16" alt=""> `+"`%s`<br><sub>%s%s</sub>", s.rel(p), hex, authored, alias), nil
}

func (s *sheet) colour() error {
	s.p("## Colour\n\nRoles first: use these, through the DaisyUI classes (`bg-base-100`, `text-base-content`, `btn-primary`) or the custom properties, never raw values.\n\n")
	roles := s.rules.Roles
	if len(roles) == 0 {
		for _, t := range s.b.Default().Tokens.List {
			if t.Type == "color" {
				roles = append(roles, brand.Role{Token: t.Name()})
			}
		}
	}
	s.p("| Role | Use | CSS |")
	for _, th := range s.b.Themes {
		s.p(" %s |", th.Config.Label)
	}
	s.p("\n|---|---|---|%s\n", strings.Repeat("---|", len(s.b.Themes)))
	for _, r := range roles {
		t := s.b.Default().Tokens.Get(r.Token)
		if t == nil {
			return fmt.Errorf("brand rules: role %s isn't a token", r.Token)
		}
		s.p("| `%s` | %s | `--%s` |", r.Token, r.Use, brand.CSSName(t))
		for _, th := range s.b.Themes {
			cell, err := s.swatchCell(th, r.Token)
			if err != nil {
				return err
			}
			s.p(" %s |", cell)
		}
		s.p("\n")
	}
	s.p("\n### Contrast\n\nEvery pair the brand declares, then the pairs brandkit adds itself: each DaisyUI colour's `-content` text on it, and `base-content` on `base-100`. Ratios are WCAG 2.x; `brandkit check` fails below the minimum. A `daisyui:` colour is whichever token that theme's DaisyUI mapping gives it, named under the ratio.\n\n| Text | On | Use | Minimum |")
	for _, th := range s.b.Themes {
		s.p(" %s |", th.Config.Label)
	}
	s.p("\n|---|---|---|---|%s\n", strings.Repeat("---|", len(s.b.Themes)))
	for _, pr := range ContrastPairs(s.b, s.rules) {
		s.p("| `%s` | `%s` | %s | %s:1 |", pr.FG, pr.BG, pr.Use, brand.Num(pr.Min))
		for _, th := range s.b.Themes {
			ratio, err := PairRatio(th, pr)
			if err != nil {
				return err
			}
			verdict := "passes"
			if ratio+1e-9 < pr.Min {
				verdict = "**fails**"
			}
			s.p(" %.2f:1 %s", ratio, verdict)
			if strings.HasPrefix(pr.FG, DaisyPrefix) || strings.HasPrefix(pr.BG, DaisyPrefix) {
				fg, _ := PairColor(th, pr.FG)
				bg, _ := PairColor(th, pr.BG)
				s.p("<br><sub>`%s` on `%s`</sub>", fg.Name(), bg.Name())
			}
			s.p(" |")
		}
		s.p("\n")
	}
	// The rest of the palette, collapsed.
	inRoles := map[string]bool{}
	for _, r := range roles {
		inRoles[r.Token] = true
	}
	var rest []*dtcg.Token
	for _, t := range s.b.Default().Tokens.List {
		if t.Type == "color" && !inRoles[t.Name()] {
			rest = append(rest, t)
		}
	}
	if len(rest) > 0 {
		s.p("\n<details>\n<summary>%s</summary>\n\n| Token | CSS |", otherColours(len(rest)))
		for _, th := range s.b.Themes {
			s.p(" %s |", th.Config.Label)
		}
		s.p("\n|---|---|%s\n", strings.Repeat("---|", len(s.b.Themes)))
		for _, t := range rest {
			s.p("| `%s` | `--%s` |", t.Name(), brand.CSSName(t))
			for _, th := range s.b.Themes {
				cell, err := s.swatchCell(th, t.Name())
				if err != nil {
					return err
				}
				s.p(" %s |", cell)
			}
			s.p("\n")
		}
		s.p("\n</details>\n")
	}
	s.p("\n")
	return nil
}

// otherColours is the summary of the collapsed table of colour tokens
// that the roles table doesn't show.
func otherColours(n int) string {
	if n == 1 {
		return "Other colours: 1 token not in the roles table"
	}
	return fmt.Sprintf("Other colours: %d tokens not in the roles table", n)
}

func (s *sheet) typeSection() error {
	s.p("## Type\n\n")
	if len(s.rules.Type) > 0 {
		s.p("Each type token at true size: the pictures are %d pixels wide, as wide as the README column, so 16px text shows at 16px.\n\n", SpecimenWidth)
	}
	s.themedPNGs("type", "Type specimen")
	if len(s.rules.Fonts) > 0 {
		s.p("| Role | Stack |\n|---|---|\n")
		for _, role := range sortedKeys(s.rules.Fonts) {
			t := s.b.Default().Tokens.Get(s.rules.Fonts[role])
			if t == nil {
				return fmt.Errorf("brand rules: font %s isn't a token", s.rules.Fonts[role])
			}
			s.p("| %s | `%s` |\n", role, brand.FontFamilyCSS(t.Value))
		}
		s.p("\n")
	}
	if len(s.rules.Type) > 0 {
		s.p("| Token | Size | Weight | Line height | Letter spacing | Family | Use |\n|---|---|---|---|---|---|---|\n")
		for _, name := range s.rules.Type {
			t := s.b.Default().Tokens.Get(name)
			if t == nil || t.Type != "typography" {
				return fmt.Errorf("brand rules: type %s isn't a typography token", name)
			}
			ds, _ := brand.Decls(t, "hex")
			fam := brand.FontFamilies(t.Value.(*dtcg.Object).Values["fontFamily"])
			s.p("| `%s` | %s | %s | %s | %s | %s | %s |\n", name, ds[1].Value, ds[2].Value, ds[4].Value, ds[3].Value, fam[0], t.Description)
		}
		s.p("\n")
	}
	if len(s.b.Config.Fonts) > 0 {
		s.p("Fonts shipped with the package:")
		for _, f := range s.b.Config.Fonts {
			s.p(" %s ([`%s`](%s)", f.Family, f.CSS, s.rel(f.CSS))
			if f.License != "" {
				s.p(", [licence](%s)", s.rel(f.License))
			}
			s.p(");")
		}
		s.w.Truncate(s.w.Len() - 1)
		s.p(".\n\n")
	}
	return nil
}

func sortedKeys(m map[string]string) []string {
	var k []string
	for x := range m {
		k = append(k, x)
	}
	for i := 1; i < len(k); i++ {
		for j := i; j > 0 && k[j] < k[j-1]; j-- {
			k[j], k[j-1] = k[j-1], k[j]
		}
	}
	return k
}

func remPx(v string) float64 {
	if n, ok := strings.CutSuffix(v, "rem"); ok {
		f, _ := strconv.ParseFloat(n, 64)
		return f * 16
	}
	n := strings.TrimSuffix(v, "px")
	f, _ := strconv.ParseFloat(n, 64)
	return f
}

func (s *sheet) scale() error {
	s.p("## Spacing and radius\n\n")
	r := s.rules
	if len(r.Spacing) == 0 && len(r.Radius) == 0 {
		s.p("The brand declares no scales.\n\n")
		return nil
	}
	if len(r.Spacing) > 0 {
		svg, err := s.spacingSheet()
		if err != nil {
			return err
		}
		s.p("**Spacing.** Each step of the spacing scale, drawn at true size as the gap (filled with `primary`) between two blocks. Use these for margins, padding and gaps.\n\n")
		s.img(s.asset("spacing.svg", svg), "Each spacing token as a labelled gap between two blocks, per theme")
		s.p("\n")
	}
	if len(r.Radius) > 0 {
		svg, err := s.radiusSheet()
		if err != nil {
			return err
		}
		s.p("**Radius.** Each corner radius, drawn on a button, a field and a card so the shapes can be compared. The line under each name says which DaisyUI components take it.\n\n")
		s.img(s.asset("radius.svg", svg), "A button, a field and a card drawn with each radius token, per theme")
		s.p("\n")
	}
	s.p("| Token | Value | Pixels |\n|---|---|---|\n")
	ds, err := s.dimens(s.b.Default(), append(append([]string(nil), r.Spacing...), r.Radius...))
	if err != nil {
		return err
	}
	for _, d := range ds {
		s.p("| `%s` | `%s` | %s |\n", d.name, d.val, brand.Num(d.px))
	}
	s.p("\n")
	return nil
}

func (s *sheet) icons() error {
	s.p("## Icons\n\n")
	ic := s.rules.Icons
	if ic == nil {
		s.p("The brand names no icon set.\n\n")
		return nil
	}
	s.p("**Set:** %s", ic.Set)
	if ic.StrokeWidth > 0 {
		s.p(", stroke width %s", brand.Num(ic.StrokeWidth))
	}
	s.p(", drawn in `currentColor` so they take the text colour.\n\n")
	if strings.EqualFold(ic.Set, "lucide") {
		sw := ic.StrokeWidth
		if sw <= 0 {
			sw = 2 // Lucide's own
		}
		svg, err := s.iconsSheet(sw)
		if err != nil {
			return err
		}
		s.p("Twelve common icons from the set (Lucide %s), in each theme's text colour (`base-content`) at 32px:\n\n", LucideVersion)
		s.img(s.asset("icons.svg", svg), "Twelve common Lucide icons with their names, per theme")
		s.p("\n")
	}
	if ic.Usage != "" {
		s.p("**In code:** `%s`.\n\n", ic.Usage)
	}
	if len(ic.Examples) > 0 {
		s.p("Common names:")
		for i, e := range ic.Examples {
			if i > 0 {
				s.p(",")
			}
			if strings.EqualFold(ic.Set, "lucide") {
				s.p(" [`%s%s`](https://lucide.dev/icons/%s)", ic.Prefix, e, e)
			} else {
				s.p(" `%s%s`", ic.Prefix, e)
			}
		}
		s.p(".\n\n")
	}
	s.p("`brandkit lint` rule R9 flags icons from another set and hand-drawn inline SVG paths in templates.\n\n")
	return nil
}

