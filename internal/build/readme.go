// ImagePaths lists the PNG specimens the README uses (relative to the package).
func ImagePaths(b *brand.Brand) []string {
	var out []string
	for _, th := range b.Themes {
		out = append(out, pathJoin(b.Config.Readme.Assets, "type-"+th.Name+".png"),
			pathJoin(b.Config.Readme.Assets, "components-"+th.Name+".png"))
	}
	return out
}

type sheet struct {
	b     *brand.Brand
	rules *brand.Rules
	files []File
	w     bytes.Buffer
	dark  *brand.Theme // shown to GitHub's dark scheme
	light *brand.Theme
}

// rel turns a package path into a path relative to the README.
func (s *sheet) rel(p string) string {
	dir := path.Dir(s.b.Config.Readme.File)
	if dir == "." {
		return p
	}
	r, err := filepath.Rel(filepath.FromSlash(dir), filepath.FromSlash(p))
	if err != nil {
		return p
	}
	return filepath.ToSlash(r)
}

func (s *sheet) asset(name string, data []byte) string {
	p := pathJoin(s.b.Config.Readme.Assets, name)
	s.files = append(s.files, File{Path: p, Data: data})
	return p
}

// picture writes a <picture> that follows the reader's GitHub theme.
func (s *sheet) picture(name func(*brand.Theme) string, alt string, width int) {
	wattr := ""
	if width > 0 {
		wattr = fmt.Sprintf(` width="%d"`, width)
	}
	if s.dark == nil || s.light == nil || s.dark == s.light {
		th := s.b.Default()
		fmt.Fprintf(&s.w, "<img alt=\"%s\" src=\"%s\"%s>\n", html.EscapeString(alt), s.rel(name(th)), wattr)
		return
	}
	fmt.Fprintf(&s.w, "<picture>\n  <source media=\"(prefers-color-scheme: dark)\" srcset=\"%s\">\n  <img alt=\"%s\" src=\"%s\"%s>\n</picture>\n",
		s.rel(name(s.dark)), html.EscapeString(alt), s.rel(name(s.light)), wattr)
}

func (s *sheet) p(format string, a ...any) { fmt.Fprintf(&s.w, format, a...) }

// Sheet writes the README brand sheet and its SVG assets.
func Sheet(b *brand.Brand) ([]File, error) {
	rules, err := b.Default().Rules()
	if err != nil {
		return nil, err
	}
	s := &sheet{b: b, rules: rules}
	for _, th := range b.Themes {
		if th.Config.GitHub == "dark" && s.dark == nil {
			s.dark = th
		}
		if th.Config.GitHub == "light" && s.light == nil {
			s.light = th
		}
	}
	c := b.Config
	s.p("<!-- %s -->\n\n# %s\n\n", generatedBy(b), c.Name)
	if c.Description != "" {
		s.p("%s\n\n", c.Description)
	}
	var names []string
	for _, th := range b.Themes {
		n := th.Config.Label
		if th.Config.Default {
			n += " (default)"
		}
		names = append(names, n)
	}
	s.p("Themes: %s. Pictures follow your GitHub theme: dark shows %s, light shows %s. Values are in the tables.\n\n",
		strings.Join(names, ", "), label(s.dark, b), label(s.light, b))
	s.p("Source: [`%s`](%s) (DTCG 2025.10). Every file below is generated by `brandkit build`; `brandkit check` checks the rules.\n\n", c.Resolver, s.rel(c.Resolver))
	s.p("1. [Logo and clear space](#logo-and-clear-space)\n2. [Colour](#colour)\n3. [Type](#type)\n4. [Spacing and radius](#spacing-and-radius)\n5. [Icons](#icons)\n6. [Components](#components)\n7. [Do and don't](#do-and-dont)\n8. [Install](#install)\n\n")
	steps := []func() error{s.logo, s.colour, s.typeSection, s.scale, s.icons, s.components, s.doDont, s.install}
	for _, f := range steps {
		if err := f(); err != nil {
			return nil, err
		}
	}
	s.files = append(s.files, File{Path: c.Readme.File, Data: s.w.Bytes()})
	return s.files, nil
}

func label(th *brand.Theme, b *brand.Brand) string {
	if th == nil {
		return b.Default().Config.Label
	}
	return th.Config.Label
}

var viewBoxRe = regexp.MustCompile(`viewBox="\s*([-\d.]+)[\s,]+([-\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)\s*"`)
var svgOpenRe = regexp.MustCompile(`(?s)<svg\b[^>]*>`)

func (s *sheet) logo() error {
	s.p("## Logo and clear space\n\n")
	r := s.rules
	if len(r.Lockup) == 0 {
		s.p("The brand declares no lockup.\n\n")
		return nil
	}
	for _, th := range s.b.Themes {
		if r.Lockup[th.Name] == "" {
			return fmt.Errorf("brand rules: no lockup for theme %s", th.Name)
		}
	}
	s.p("Use the lockup made for the ground it sits on:\n\n| Theme | Lockup |\n|---|---|\n")
	for _, th := range s.b.Themes {
		s.p("| %s | [`%s`](%s) |\n", th.Config.Label, r.Lockup[th.Name], s.rel(r.Lockup[th.Name]))
	}
	s.p("\n")
	ratio := 0.0
	if r.ClearSpace != nil {
		ratio = r.ClearSpace.Ratio
	}
	for _, th := range s.b.Themes {
		svg, err := s.clearSpaceSVG(th, ratio)
		if err != nil {
			return err
		}
		s.asset("clearspace-"+th.Name+".svg", svg)
	}
	s.picture(func(th *brand.Theme) string { return pathJoin(s.b.Config.Readme.Assets, "clearspace-"+th.Name+".svg") }, "The lockup with its clear space marked", 0)
	s.p("\n")
	if r.ClearSpace != nil {
		s.p("**Clear space:** %s× the %s on every side (the dashed box).", brand.Num(r.ClearSpace.Ratio), r.ClearSpace.Of)
		if r.ClearSpace.Note != "" {
			s.p(" %s", r.ClearSpace.Note)
		}
		s.p("\n\n")
	}
	if r.Mark != "" {
		s.p("The mark on its own: [`%s`](%s).\n\n", r.Mark, s.rel(r.Mark))
	}
	return nil
}

func (s *sheet) clearSpaceSVG(th *brand.Theme, ratio float64) ([]byte, error) {
	src, err := os.ReadFile(filepath.Join(s.b.Dir, filepath.FromSlash(s.rules.Lockup[th.Name])))
	if err != nil {
		return nil, err
	}
	open := svgOpenRe.Find(src)
	m := viewBoxRe.FindSubmatch(open)
	if m == nil {
		return nil, fmt.Errorf("%s: the lockup needs a viewBox", s.rules.Lockup[th.Name])
	}
	w, _ := strconv.ParseFloat(string(m[3]), 64)
	h, _ := strconv.ParseFloat(string(m[4]), 64)
	inner := bytes.TrimSpace(src[bytes.Index(src, open)+len(open):])
	inner = bytes.TrimSuffix(inner, []byte("</svg>"))
	pad := ratio * h
	margin := 16.0
	W, H := w+2*pad+2*margin, h+2*pad+2*margin
	bg := s.roleHex(th, "base-100", "#ffffff")
	line := s.roleHex(th, "base-content", "#000000")
	var out bytes.Buffer
	fmt.Fprintf(&out, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %s %s" width="%s" height="%s">`, brand.Num(W), brand.Num(H), brand.Num(W*2), brand.Num(H*2))
	fmt.Fprintf(&out, `<rect width="%s" height="%s" rx="8" fill="%s"/>`, brand.Num(W), brand.Num(H), bg)
	fmt.Fprintf(&out, `<rect x="%s" y="%s" width="%s" height="%s" fill="none" stroke="%s" stroke-opacity="0.6" stroke-dasharray="4 3"/>`,
		brand.Num(margin), brand.Num(margin), brand.Num(w+2*pad), brand.Num(h+2*pad), line)
	fmt.Fprintf(&out, `<svg x="%s" y="%s" width="%s" height="%s" viewBox="%s %s %s %s">%s</svg></svg>`+"\n",
		brand.Num(margin+pad), brand.Num(margin+pad), brand.Num(w), brand.Num(h), m[1], m[2], m[3], m[4], inner)
	return out.Bytes(), nil
}

// roleHex is a DaisyUI role's hex in a theme, for drawing sheet assets.
func (s *sheet) roleHex(th *brand.Theme, role, fallback string) string {
	dt, err := DaisyVars(th, "hex")
	if err != nil {
		return fallback
	}
	for _, d := range dt.Vars {
		if d.Name == "color-"+role {
			return d.Value
		}
	}
	return fallback
}

// swatch writes one swatch file per distinct colour.
func (s *sheet) swatch(hex string) string {
	p := pathJoin(s.b.Config.Readme.Assets, "sw-"+strings.TrimPrefix(hex, "#")+".svg")
	for _, f := range s.files {
		if f.Path == p {
			return p
		}
	}
	s.files = append(s.files, File{Path: p, Data: swatchSVG(hex)})
	return p
}

func swatchSVG(hex string) []byte {
	return []byte(fmt.Sprintf(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24"><rect x="0.5" y="0.5" width="23" height="23" rx="4" fill="%s" stroke="#8c959f" stroke-opacity="0.6"/></svg>`+"\n", hex))
}

func colourText(t *dtcg.Token) (string, string, error) {
	hex, err := brand.ColorCSS(t.Value, "hex")
	if err != nil {
		return "", "", err
	}
	o := t.Value.(*dtcg.Object)
	comps, _ := o.Values["components"].([]any)
	parts := make([]string, len(comps))
	for i, c := range comps {
		if f, ok := c.(float64); ok {
			parts[i] = brand.Num(f)
		} else {
			parts[i] = "none"
		}
	}
	return hex, fmt.Sprintf("%s(%s)", o.String("colorSpace"), strings.Join(parts, " ")), nil
}

func (s *sheet) swatchCell(th *brand.Theme, name string) (string, error) {
	t := th.Tokens.Get(name)
	if t == nil || t.Type != "color" {
		return "", fmt.Errorf("theme %s: %s isn't a colour token", th.Name, name)
	}
	hex, authored, err := colourText(t)
	if err != nil {
		return "", err
	}
	p := s.swatch(hex)
	alias := ""
	if t.Alias != "" {
		alias = fmt.Sprintf(" ← `%s`", t.Alias)
	}
	return fmt.Sprintf(`<img src="%s" width="16" height="16" alt=""> `+"`%s`<br><sub>%s%s</sub>", s.rel(p), hex, authored, alias), nil
}

func (s *sheet) colour() error {
	s.p("## Colour\n\nRoles first: use these, through the DaisyUI classes (`bg-base-100`, `text-base-content`, `btn-primary`) or the custom properties, never raw values.\n\n")
	roles := s.rules.Roles
	if len(roles) == 0 {
		for _, t := range s.b.Default().Tokens.List {
			if t.Type == "color" {
				roles = append(roles, brand.Role{Token: t.Name()})
			}
		}
	}
	s.p("| Role | Use | CSS |")
	for _, th := range s.b.Themes {
		s.p(" %s |", th.Config.Label)
	}
	s.p("\n|---|---|---|%s\n", strings.Repeat("---|", len(s.b.Themes)))
	for _, r := range roles {
		t := s.b.Default().Tokens.Get(r.Token)
		if t == nil {
			return fmt.Errorf("brand rules: role %s isn't a token", r.Token)
		}
		s.p("| `%s` | %s | `--%s` |", r.Token, r.Use, brand.CSSName(t))
		for _, th := range s.b.Themes {
			cell, err := s.swatchCell(th, r.Token)
			if err != nil {
				return err
			}
			s.p(" %s |", cell)
		}
		s.p("\n")
	}
	s.p("\n### Contrast\n\nEvery pair the brand declares, by the WCAG 2.x ratio (`brandkit check` fails below the minimum).\n\n| Text | On | Use | Minimum |")
	for _, th := range s.b.Themes {
		s.p(" %s |", th.Config.Label)
	}
	s.p("\n|---|---|---|---|%s\n", strings.Repeat("---|", len(s.b.Themes)))
	for _, pr := range s.rules.Contrast {
		s.p("| `%s` | `%s` | %s | %s:1 |", pr.FG, pr.BG, pr.Use, brand.Num(pr.Min))
		for _, th := range s.b.Themes {
			ratio, err := PairRatio(th, pr)
			if err != nil {
				return err
			}
			verdict := "passes"
			if ratio+1e-9 < pr.Min {
				verdict = "**fails**"
			}
			s.p(" %.2f:1 %s |", ratio, verdict)
		}
		s.p("\n")
	}
	// The rest of the palette, collapsed.
	inRoles := map[string]bool{}
	for _, r := range roles {
		inRoles[r.Token] = true
	}
	var rest []*dtcg.Token
	for _, t := range s.b.Default().Tokens.List {
		if t.Type == "color" && !inRoles[t.Name()] {
			rest = append(rest, t)
		}
	}
	if len(rest) > 0 {
		s.p("\n<details>\n<summary>The full palette (%d colours)</summary>\n\n| Token | CSS |", len(rest))
		for _, th := range s.b.Themes {
			s.p(" %s |", th.Config.Label)
		}
		s.p("\n|---|---|%s\n", strings.Repeat("---|", len(s.b.Themes)))
		for _, t := range rest {
			s.p("| `%s` | `--%s` |", t.Name(), brand.CSSName(t))
			for _, th := range s.b.Themes {
				cell, err := s.swatchCell(th, t.Name())
				if err != nil {
					return err
				}
				s.p(" %s |", cell)
			}
			s.p("\n")
		}
		s.p("\n</details>\n")
	}
	s.p("\n")
	return nil
}

// PairRatio is a declared pair's WCAG ratio in a theme, the foreground
// composited over the background.
func PairRatio(th *brand.Theme, pr brand.ContrastPair) (float64, error) {
	fg, bg := th.Tokens.Get(pr.FG), th.Tokens.Get(pr.BG)
	if fg == nil || bg == nil || fg.Type != "color" || bg.Type != "color" {
		return 0, fmt.Errorf("theme %s: contrast pair %s on %s needs two colour tokens", th.Name, pr.FG, pr.BG)
	}
	f, err := brand.ColorRGB(fg.Value)
	if err != nil {
		return 0, err
	}
	b, err := brand.ColorRGB(bg.Value)
	if err != nil {
		return 0, err
	}
	b.A = 1
	return color.Contrast(f.Over(b), b), nil
}

func (s *sheet) typeSection() error {
	s.p("## Type\n\n")
	s.picture(func(th *brand.Theme) string { return pathJoin(s.b.Config.Readme.Assets, "type-"+th.Name+".png") }, "Type specimen", 800)
	s.p("\n")
	if len(s.rules.Fonts) > 0 {
		s.p("| Role | Stack |\n|---|---|\n")
		for _, role := range sortedKeys(s.rules.Fonts) {
			t := s.b.Default().Tokens.Get(s.rules.Fonts[role])
			if t == nil {
				return fmt.Errorf("brand rules: font %s isn't a token", s.rules.Fonts[role])
			}
			s.p("| %s | `%s` |\n", role, brand.FontFamilyCSS(t.Value))
		}
		s.p("\n")
	}
	if len(s.rules.Type) > 0 {
		s.p("| Token | Size | Weight | Line height | Letter spacing | Family | Use |\n|---|---|---|---|---|---|---|\n")
		for _, name := range s.rules.Type {
			t := s.b.Default().Tokens.Get(name)
			if t == nil || t.Type != "typography" {
				return fmt.Errorf("brand rules: type %s isn't a typography token", name)
			}
			ds, _ := brand.Decls(t, "hex")
			fam := brand.FontFamilies(t.Value.(*dtcg.Object).Values["fontFamily"])
			s.p("| `%s` | %s | %s | %s | %s | %s | %s |\n", name, ds[1].Value, ds[2].Value, ds[4].Value, ds[3].Value, fam[0], t.Description)
		}
		s.p("\n")
	}
	if len(s.b.Config.Fonts) > 0 {
		s.p("Fonts shipped with the package:")
		for _, f := range s.b.Config.Fonts {
			s.p(" %s ([`%s`](%s)", f.Family, f.CSS, s.rel(f.CSS))
			if f.License != "" {
				s.p(", [licence](%s)", s.rel(f.License))
			}
			s.p(");")
		}
		s.w.Truncate(s.w.Len() - 1)
		s.p(".\n\n")
	}
	return nil
}

func sortedKeys(m map[string]string) []string {
	var k []string
	for x := range m {
		k = append(k, x)
	}
	for i := 1; i < len(k); i++ {
		for j := i; j > 0 && k[j] < k[j-1]; j-- {
			k[j], k[j-1] = k[j-1], k[j]
		}
	}
	return k
}

func remPx(v string) float64 {
	if n, ok := strings.CutSuffix(v, "rem"); ok {
		f, _ := strconv.ParseFloat(n, 64)
		return f * 16
	}
	n := strings.TrimSuffix(v, "px")
	f, _ := strconv.ParseFloat(n, 64)
	return f
}

func (s *sheet) scale() error {
	s.p("## Spacing and radius\n\n")
	r := s.rules
	if len(r.Spacing) == 0 && len(r.Radius) == 0 {
		s.p("The brand declares no scales.\n\n")
		return nil
	}
	type item struct{ name, val string }
	get := func(names []string) ([]item, error) {
		var out []item
		for _, n := range names {
			t := s.b.Default().Tokens.Get(n)
			if t == nil || t.Type != "dimension" {
				return nil, fmt.Errorf("brand rules: %s isn't a dimension token", n)
			}
			ds, _ := brand.Decls(t, "hex")
			out = append(out, item{n, ds[0].Value})
		}
		return out, nil
	}
	sp, err := get(r.Spacing)
	if err != nil {
		return err
	}
	rd, err := get(r.Radius)
	if err != nil {
		return err
	}
	for _, th := range s.b.Themes {
		fg := s.roleHex(th, "primary", "#888888")
		txt := s.roleHex(th, "base-content", "#000000")
		bg := s.roleHex(th, "base-100", "#ffffff")
		box := s.roleHex(th, "base-200", "#eeeeee")
		line := s.roleHex(th, "neutral", "#999999")
		var w bytes.Buffer
		rowH, top := 28.0, 16.0
		height := top + float64(len(sp))*rowH + 24 + 96
		fmt.Fprintf(&w, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 %s" width="640" height="%s" font-family="system-ui, -apple-system, Segoe UI, sans-serif" font-size="13">`, brand.Num(height), brand.Num(height))
		fmt.Fprintf(&w, `<rect width="640" height="%s" rx="8" fill="%s"/>`, brand.Num(height), bg)
		for i, it := range sp {
			y := top + float64(i)*rowH
			fmt.Fprintf(&w, `<text x="16" y="%s" fill="%s">%s</text>`, brand.Num(y+14), txt, html.EscapeString(it.name+"  "+it.val))
			fmt.Fprintf(&w, `<rect x="180" y="%s" width="%s" height="16" fill="%s"/>`, brand.Num(y+2), brand.Num(remPx(it.val)*4), fg)
		}
		y := top + float64(len(sp))*rowH + 16
		x := 16.0
		for _, it := range rd {
			rr := remPx(it.val)
			fmt.Fprintf(&w, `<rect x="%s" y="%s" width="120" height="56" rx="%s" fill="%s" stroke="%s"/>`, brand.Num(x), brand.Num(y), brand.Num(rr), box, line)
			fmt.Fprintf(&w, `<text x="%s" y="%s" fill="%s">%s</text>`, brand.Num(x+10), brand.Num(y+76), txt, html.EscapeString(it.name+"  "+it.val))
			x += 160
		}
		w.WriteString("</svg>\n")
		s.asset("scale-"+th.Name+".svg", w.Bytes())
	}
	s.picture(func(th *brand.Theme) string { return pathJoin(s.b.Config.Readme.Assets, "scale-"+th.Name+".svg") }, "Spacing bars (drawn 4× size) and radius samples", 640)
	s.p("\n| Token | Value |\n|---|---|\n")
	for _, it := range append(sp, rd...) {
		s.p("| `%s` | `%s` |\n", it.name, it.val)
	}
	s.p("\n")
	return nil
}

func (s *sheet) icons() error {
	s.p("## Icons\n\n")
	ic := s.rules.Icons
	if ic == nil {
		s.p("The brand names no icon set.\n\n")
		return nil
	}
	s.p("**Set:** %s", ic.Set)
	if ic.StrokeWidth > 0 {
		s.p(", stroke width %s", brand.Num(ic.StrokeWidth))
	}
	s.p(", drawn in `currentColor` so they take the text colour.\n\n")
	if ic.Usage != "" {
		s.p("**In code:** `%s`.\n\n", ic.Usage)
	}
	if len(ic.Examples) > 0 {
		s.p("Common names:")
		for i, e := range ic.Examples {
			if i > 0 {
				s.p(",")
			}
			if strings.EqualFold(ic.Set, "lucide") {
				s.p(" [`%s%s`](https://lucide.dev/icons/%s)", ic.Prefix, e, e)
			} else {
				s.p(" `%s%s`", ic.Prefix, e)
			}
		}
		s.p(".\n\n")
	}
	s.p("`brandkit lint` rule R9 flags icons from another set and hand-drawn inline SVG paths in templates.\n\n")
	return nil
}

