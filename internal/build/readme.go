func (s *sheet) doDont() error {
	s.p("## Do and don't\n\n")
	if len(s.rules.Do) == 0 && len(s.rules.Dont) == 0 {
		s.p("No rules declared.\n\n")
		return nil
	}
	s.p("| Do | Don't |\n|---|---|\n")
	n := max(len(s.rules.Do), len(s.rules.Dont))
	for i := range n {
		var d, x string
		if i < len(s.rules.Do) {
			d = s.rules.Do[i]
		}
		if i < len(s.rules.Dont) {
			x = s.rules.Dont[i]
		}
		s.p("| %s | %s |\n", strings.ReplaceAll(d, "|", `\|`), strings.ReplaceAll(x, "|", `\|`))
	}
	s.p("\n")
	if a := s.rules.Accent; a != nil && a.Note != "" {
		s.p("**Accent:** %s\n\n", a.Note)
	}
	if s.rules.Shadows == "none" {
		s.p("**Shadows:** none. The Tailwind theme removes the shadow utilities and `brandkit lint` rule R7 flags any that remain.\n\n")
	}
	return nil
}

func (s *sheet) install() error {
	c := s.b.Config
	repo := c.Repo
	if repo == "" {
		repo = "<owner>/<repo>"
	}
	out := func(f string) string { return pathJoin(c.Out, f) }
	s.p("## Install\n\n```sh\nmise use github:shermanhuman/brandkit\nbrandkit install %s@<tag>   # vendors the files below and writes brandkit.lock\nbrandkit update                     # moves to the newest tag\n```\n\n", repo)
	s.p("| File | What it's for |\n|---|---|\n")
	s.p("| [`%s`](%s) | colour custom properties, per theme |\n", out(c.TokensCSS.File), s.rel(out(c.TokensCSS.File)))
	s.p("| [`%s`](%s) | type, spacing, radius and motion custom properties |\n", out(c.BrandCSS.File), s.rel(out(c.BrandCSS.File)))
	s.p("| [`%s`](%s) | DaisyUI themes for a prebuilt `daisyui.css` (`[data-theme]` blocks) |\n", out(c.DaisyUI.ThemesCSS), s.rel(out(c.DaisyUI.ThemesCSS)))
	s.p("| [`%s`](%s) | DaisyUI themes for Tailwind 4 with vendored `daisyui.js` (`@plugin` blocks; removes Tailwind's default palette) |\n", out(c.DaisyUI.PluginCSS), s.rel(out(c.DaisyUI.PluginCSS)))
	s.p("| [`%s`](%s) | what `brandkit lint` checks against |\n\n", out(c.Lint), s.rel(out(c.Lint)))
	names := make([]string, 0, len(s.b.Themes))
	for _, th := range s.b.Themes {
		names = append(names, "`"+th.Config.DaisyUI+"`")
	}
	s.p("Select a theme with `data-theme` on `<html>`: %s.\n", strings.Join(names, ", "))
	return nil
}
